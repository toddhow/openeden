#ifndef VSGUTIL_SLANGRUNTIME_H
#define VSGUTIL_SLANGRUNTIME_H

#include <cstdint>
#include <filesystem>
#include <functional>
#include <memory>
#include <mutex>
#include <set>
#include <string>
#include <vector>

#include <vsg/core/Inherit.h>
#include <vsg/core/Object.h>

/*
 * Task 0072, stage h (toddhow, 2026-11-04: "Yes ship it"): the Slang compiler in the game. With `[Rendering] slang
 * shaders` on, a define set that has no prebuilt permutation (vsgUtil::findSlangPermutation) is compiled at run time
 * from the `.slang` sources, with the flags of the build (files/shaders/CMakeLists.txt, openeden_add_slang_
 * permutations), and the result is cached on disk under the user data folder.
 *
 * Who owns what: a SlangRuntime lives on the shader vsg::Options (slangRuntimeKey) and is made only when the setting
 * is on; the library is loaded by the first compile, never before, so with the setting off nothing is loaded. The
 * compiler behind it is an interface, so that the cache, the self-test and the failure rules are tested without the
 * library. Threads: obtain() may be called from any thread (pipelines are made on loading threads); compiles are
 * serialised, because one Slang global session is not thread-safe (slang.h, IGlobalSession).
 */
namespace vsgUtil
{
    /// The name of the SlangRuntime object on the shader options.
    inline constexpr const char* slangRuntimeKey = "openeden.slangRuntime";

    /// What the build knew about a stage file, from "<stage file>.slang-stage" (generated by
    /// openeden_add_slang_permutations): the Slang source relative to the shader folder, its entry point and stage.
    struct SlangStageInfo
    {
        std::string mSource;
        std::string mEntry;
        std::string mStage;
    };

    /// "<source>\t<entry>\t<stage>" and a newline; throws std::invalid_argument on anything else.
    SlangStageInfo parseSlangStageInfo(const std::string& text);

    struct SlangRuntimeRequest
    {
        std::string mStageFile; // "default/main.frag"
        SlangStageInfo mInfo;
        std::set<std::string> mDefines; // the canonical set, "UVSETS_<n>" included, as the build passes them with -D
        std::filesystem::path mShaderRoot; // the folder holding the .slang files
    };

    /// The compiler itself. Implementations need not be thread safe: SlangRuntime serialises the calls.
    class SlangRuntimeCompiler
    {
    public:
        virtual ~SlangRuntimeCompiler() = default;
        /// What identifies this compiler and its flags in a cache key, worked out without starting it (so a run with a
        /// warm cache never loads the library): for the dynamic compiler the size and time of its library files;
        /// empty when it cannot be used (the files are missing).
        virtual std::string cacheIdentity() = 0;
        /// SPIR-V words, or empty with the reason in `error`.
        virtual std::vector<uint32_t> compile(const SlangRuntimeRequest& request, std::string& error) = 0;
    };

    /// The compiler that loads the Slang library from `libraryDirectory` (slang.dll and its two siblings on Windows,
    /// the .so files on Linux) the first time compile() is called. Without the library headers at build
    /// time (OPENEDEN_SLANG_RUNTIME not defined) every call fails with a reason.
    std::unique_ptr<SlangRuntimeCompiler> createDynamicSlangCompiler(const std::filesystem::path& libraryDirectory);

    /// What the caller checks on a freshly compiled result before it is used and cached: empty when fine, else the
    /// reason it is refused. `mKey` is text that goes into the cache key (the GLSL the result was checked against).
    struct SlangRuntimeCheck
    {
        std::string mKey;
        std::function<std::string(const std::vector<uint32_t>& words)> mCheck;
    };

    class SlangRuntime : public vsg::Inherit<vsg::Object, SlangRuntime>
    {
    public:
        /// `cacheDirectory` may be empty: nothing is cached then.
        SlangRuntime(std::unique_ptr<SlangRuntimeCompiler> compiler, std::filesystem::path cacheDirectory);
        ~SlangRuntime() override;

        /// Where the lines about a failure (`warning` true) and the summary at the end (false) go (the game gives its
        /// log: VSG's own logger writes to stderr, which openmw.log does not show). Without one, vsg::warn or
        /// vsg::info.
        void setLog(std::function<void(bool warning, const std::string&)> log);

        /// The self-test the first compile runs: `request` is compiled and its words must equal `expected`, the
        /// permutation the build shipped for it. Without a test set (or when it fails) the runtime is disabled.
        void setSelfTest(SlangRuntimeRequest request, std::vector<uint32_t> expected);

        /// SPIR-V for the request, from the cache or compiled now; empty when the runtime is disabled, the compile
        /// fails or `check` refuses the result (logged once per stage file and set). Never throws.
        std::vector<uint32_t> obtain(const SlangRuntimeRequest& request, const SlangRuntimeCheck& check) const;

        /// True after a failed self-test or a compiler that cannot start: obtain() then returns nothing at once.
        bool disabled() const;

        struct Stats
        {
            std::size_t mCompiled = 0;
            std::size_t mCacheHits = 0;
            std::size_t mFailed = 0;
            double mCompileMilliseconds = 0;
            double mCacheMilliseconds = 0;
        };
        Stats stats() const;

        /// The cache key text of a request (everything the result depends on), and its file name. Public for tests.
        std::string keyText(const SlangRuntimeRequest& request, const SlangRuntimeCheck& check) const;
        static std::string fileNameOf(const std::string& keyText);

    private:
        struct State;
        std::unique_ptr<State> mState;
    };
}

#endif
