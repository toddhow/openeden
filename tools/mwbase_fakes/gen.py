#!/usr/bin/env python3
"""Generates test doubles for the pure virtual functions of an MWBase interface (task 0085, move 2, stage 2b).

usage: gen.py <header> <ClassName> <GeneratedBaseName>  > out.inc

Every pure virtual function of <ClassName> becomes an override that calls `unexpectedCall("<ClassName>::<name>")`,
which throws. A test fake derives from the generated base and overrides the few functions the code under test uses.
The output is committed (apps/openmw_tests/mwmechanics/fakes/); regenerate it when an MWBase interface changes.
"""
import re
import sys


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def split_top(text):
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch in "(<[{":
            depth += 1
        elif ch in ")>]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return parts


def main():
    header, cls, base = sys.argv[1], sys.argv[2], sys.argv[3]
    text = strip_comments(open(header, encoding="utf-8").read())
    m = re.search(r"class\s+%s\b[^{;]*\{" % re.escape(cls), text)
    body = text[m.end():]
    out = []
    seen = set()
    text = re.sub(r"=\s*\{\}", "= X", body)  # a braced default argument
    for stmt in re.split(r"[;{}]", text):
        stmt = " ".join(stmt.split())
        stmt = re.sub(r"^(public|protected|private)\s*:\s*", "", stmt)
        if "(" not in stmt or not re.search(r"=\s*0$", stmt):
            continue
        stmt = re.sub(r"\s*=\s*0$", "", stmt)
        stmt = re.sub(r"\s+override$", "", stmt)
        stmt = re.sub(r"^virtual\s+", "", stmt)
        d = stmt
        if d.startswith("~"):
            continue
        # name( params ) qualifiers
        open_idx = None
        depth = 0
        # find the '(' that follows the function name: the first '(' at angle depth 0
        angle = 0
        for i, ch in enumerate(d):
            if ch == "<":
                angle += 1
            elif ch == ">":
                angle -= 1
            elif ch == "(" and angle == 0:
                open_idx = i
                break
        head = d[:open_idx].rstrip()
        mm = re.match(r"(.*?)([A-Za-z_]\w*)$", head)
        ret, name = mm.group(1).strip(), mm.group(2)
        # matching ')'
        depth = 0
        for j in range(open_idx, len(d)):
            if d[j] == "(":
                depth += 1
            elif d[j] == ")":
                depth -= 1
                if depth == 0:
                    close_idx = j
                    break
        params = d[open_idx + 1:close_idx]
        quals = d[close_idx + 1:].strip()
        plist = []
        for p in split_top(params):
            p = p.strip()
            if not p:
                continue
            p = re.sub(r"\s*=\s*.*$", "", p)  # drop the default argument
            plist.append(p)
        sig = "%s %s(%s) %s override" % (ret, name, ", ".join(plist), quals)
        sig = " ".join(sig.split()).replace("( ", "(")
        key = (name, ", ".join(plist), quals)
        if key in seen:
            continue
        seen.add(key)
        out.append("    %s\n    {\n        unexpectedCall(\"%s::%s\");\n    }\n" % (sig, cls, name))
    sys.stdout.write("// Generated by tools/mwbase_fakes/gen.py from %s; do not edit by hand.\n" % header.replace("\\", "/").split("apps/")[-1])
    sys.stdout.write("// Every pure virtual function of MWBase::%s, throwing. Derive and override what a test uses.\n" % cls)
    sys.stdout.write("class %s : public MWBase::%s\n{\npublic:\n" % (base, cls))
    sys.stdout.write("\n".join(out))
    sys.stdout.write("};\n")


main()
