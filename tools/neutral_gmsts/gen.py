#!/usr/bin/env python3
"""Regenerates apps/openmw/mwworld/neutralgmsts.inc from the editor's default GMST table (task 0107).

The table in apps/opencs/model/world/defaultgmsts.cpp holds Morrowind's default values for the numeric game
settings. A neutral-world session (a game whose plugins define none of them) gets the missing ones as static records so
that the engine's Morrowind-shaped start-up finds what it reads. Run from the repository root:
    python tools/neutral_gmsts/gen.py
"""
import re

SRC = 'apps/opencs/model/world/defaultgmsts.cpp'
OUT = 'apps/openmw/mwworld/neutralgmsts.inc'

lines = open(SRC, encoding='utf8').read().replace('\r', '').split('\n')


def start_of(name):
    for i, line in enumerate(lines):
        if name + '[' in line and '= {' in line:
            return i + 1
    raise SystemExit('not found: ' + name)


def grab(start, pattern):
    out = []
    for line in lines[start:]:
        if line.startswith('};'):
            break
        m = re.match(pattern, line)
        if m:
            out.append(m.groups())
    return out


floats = grab(start_of('FloatsDefaultValues'), r'^\s*(-?[0-9.]+f?),\s*//\s*(\w+)')
ints = grab(start_of('IntsDefaultValues'), r'^\s*(-?[0-9]+),\s*//\s*(\w+)')
with open(OUT, 'w', newline='\n') as f:
    f.write('// Generated by tools/neutral_gmsts/gen.py from %s. Do not edit.\n' % SRC)
    f.write('// Morrowind\'s default values of the numeric game settings (OpenMW-CS\'s table for new content).\n')
    f.write('constexpr std::array<NeutralFloatGmst, %d> sNeutralFloatGmsts{ {\n' % len(floats))
    for value, name in floats:
        f.write('    { "%s", %s },\n' % (name, value if value.endswith('f') else value + 'f'))
    f.write('} };\n')
    f.write('constexpr std::array<NeutralIntGmst, %d> sNeutralIntGmsts{ {\n' % len(ints))
    for value, name in ints:
        f.write('    { "%s", %s },\n' % (name, value))
    f.write('} };\n')
print(len(floats), len(ints))
